//! Акаунти вторинного ринку. Схема — docs/PLAN.md → «Модель даних».
//!
//! Тут один акаунт, і він переїхав сюди з ядра разом із самою вторинкою:
//! `Offer` пишеться цією програмою, тому їй же й належить. Ядро його не читає —
//! облік бонда не залежить від того, стоїть він на продажу чи ні.

use anchor_lang::prelude::*;

pub const OFFER_SEED: &[u8] = b"offer";
/// Сховище оферти — PDA від самої оферти: адресу мусить знаходити будь-хто, хто
/// бачить оферту, а не лише той, хто її виставляв.
pub const ESCROW_SEED: &[u8] = b"escrow";
/// USDC-рахунок оферти. Живе рівно одну інструкцію — стільки, скільки треба,
/// щоб провести через нього накопичене за час оферти: `claim` віддає виплату
/// лише на рахунок власника обліку, а власник тут — PDA оферти.
pub const PROCEEDS_SEED: &[u8] = b"proceeds";

/// Оферта вторинного ринку. Seeds `["offer", issue, seller, nonce]`.
///
/// `nonce` у seeds — щоб у продавця могло стояти кілька оферт на один випуск, і
/// щоб адресу оферти можна було повторити, маючи на руках сам акаунт
/// (docs/PLAN.md → «Модель даних»).
#[account]
#[derive(InitSpace)]
pub struct Offer {
    pub seller: Pubkey,
    pub issue: Pubkey,
    pub amount: u64,
    pub price: u64,
    /// Токени лежать тут до купівлі або скасування — подвійний продаж
    /// неможливий (`FR-025`). Authority рахунку — PDA самої оферти, і саме
    /// тому вторинка не може жити в ядрі: підписати за цей PDA мусить
    /// програма, а ядро в CPI по мінту бонда впирається в свій же гук.
    pub token_escrow: Pubkey,
    pub nonce: u64,
    pub bump: u8,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn account_sizes_are_pinned() {
        // PLAN рахує розміри під rent-exempt. Поле, додане мимохідь, має бути
        // видно як зміну цифри, а не тільки як зрослу оренду.
        assert_eq!(Offer::INIT_SPACE, 121);
    }
}
